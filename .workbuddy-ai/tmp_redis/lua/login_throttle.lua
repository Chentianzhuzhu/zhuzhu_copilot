-- ============================================================
-- login_throttle.lua  登录失败限流 + 账号锁定
-- 用途：账号密码登录的暴力破解防护
-- KEYS[1] = 失败计数键，如 login:fail:{account}
-- KEYS[2] = 锁定标记键，如 login:lock:{account}
-- ARGV[1] = 允许的最大失败次数（如 5）
-- ARGV[2] = 计数窗口秒数（如 900，15分钟）
-- ARGV[3] = 锁定时长秒数（如 1800）
-- 返回   0 = 仍然允许尝试
--       n>0 = 本次是第 n 次失败，仍未到阈值
--       -1 = 已达阈值，本次触发锁定
--       -2 = 账号已被锁定，直接拒绝
-- ------------------------------------------------------------
-- 用法：
--   登录前先调用，若返回 -2 直接拒绝登录；
--   返回 0 或正数则允许本次尝试，失败时由调用方再次调用累加；
--   登录成功时删除 KEYS[1] 与 KEYS[2]（清计数）。
-- 计数键带窗口TTL，超过窗口自动清零，无需人工重置。
-- ============================================================
if redis.call('EXISTS', KEYS[2]) == 1 then
    return -2
end

local n = redis.call('INCR', KEYS[1])
if n == 1 then
    redis.call('EXPIRE', KEYS[1], ARGV[2])
end

if n >= tonumber(ARGV[1]) then
    redis.call('SET', KEYS[2], '1', 'EX', ARGV[3])
    return -1
end

return n
