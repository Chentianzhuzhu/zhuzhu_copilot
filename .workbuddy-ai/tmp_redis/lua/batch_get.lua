-- ============================================================
-- batch_get.lua  批量读缓存（大幅省往返）
-- 用途：订单列表、用户资料等多key一次性取回
-- 适用场景：客户端到Redis公网延迟高（数十ms），
--           逐条 GET 会完全抵消缓存的收益。
-- KEYS = 任意数量的缓存键
-- 返回 = 与 KEYS 等长的数组；命中返回字符串，未命中返回 false
-- ------------------------------------------------------------
-- 相比 MGET 的优势：可在脚本内按需改造数据、可跨库打包；
-- 相比逐条 GET 的优势：一次网络往返拿到全部结果。
-- ============================================================
local result = {}
for i = 1, #KEYS do
    local v = redis.call('GET', KEYS[i])
    if v == false then
        result[i] = false
    else
        result[i] = v
    end
end
return result
