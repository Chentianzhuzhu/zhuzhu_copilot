-- ============================================================
-- order_dedup.lua  订单幂等去重
-- 用途：高并发下防止同一请求重复下单/重复扣减
-- KEYS[1] = 幂等键，如 idem:order:{userId}:{requestId}
-- ARGV[1] = 过期秒数（幂等窗口，建议 600~86400）
-- 返回  1 = 首次请求，已占用；0 = 重复请求，应拒绝
-- ------------------------------------------------------------
-- 为什么用 SET NX EX：原子占位，不怕并发时两个请求同时通过
-- if-exists 判断。窗口到期后Redis自动清理，无需额外GC。
-- ============================================================
if redis.call('SET', KEYS[1], '1', 'NX', 'EX', ARGV[1]) then
    return 1
end
return 0
